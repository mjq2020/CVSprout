"""Compile the shared JSON catalog to a browser ES module (no build dependency)."""
import ast
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]


def compiled_catalog():
    catalog = json.loads((ROOT / "static/locales/en.json").read_text())
    return "// Generated by scripts/build_locales.py; edit en.json instead.\nexport default " + json.dumps(catalog, ensure_ascii=False, indent=2) + ";\n"


def python_messages(node, parent=None):
    value = None
    if isinstance(node, ast.JoinedStr):
        parts, count = [], 0
        for part in node.values:
            if isinstance(part, ast.Constant):
                parts.append(str(part.value))
            else:
                parts.append("{" + str(count) + "}")
                count += 1
        value = "".join(parts)
    elif isinstance(node, ast.Constant) and isinstance(node.value, str):
        if not isinstance(parent, (ast.JoinedStr, ast.Expr)):
            value = node.value
    if value and re.search(r"[\u3400-\u9fff]", value):
        if re.search(r"\b(SELECT|INSERT|UPDATE|CREATE TABLE)\b", value):
            yield from (literal for literal in re.findall(r"'([^'\n]*)'", value) if re.search(r"[\u3400-\u9fff]", literal))
        elif not value.startswith("你是严格的图像数据标注器。"):
            yield value
    for child in ast.iter_child_nodes(node):
        yield from python_messages(child, node)


def compiled_api_rules():
    # Share the exact field rules and backend templates with the browser so it
    # can also display responses from a server awaiting a normal restart.
    sys.path.insert(0, str(ROOT)) if str(ROOT) not in sys.path else None
    from app.i18n import MESSAGE_FIELDS, USER_FIELDS, SYSTEM_CONTAINERS, MESSAGE_SLOTS
    templates = {source for path in (ROOT / "app").rglob("*.py")
                 for source in python_messages(ast.parse(path.read_text())) if re.search(r"\{\d+\}", source)}
    templates.add("{0}（本地 AI）")
    rules = {"message_fields": sorted(MESSAGE_FIELDS), "user_fields": sorted(USER_FIELDS),
             "system_containers": sorted(SYSTEM_CONTAINERS), "message_slots": MESSAGE_SLOTS,
             "templates": sorted(templates, key=lambda source: (-len(re.sub(r"\{\d+\}", "", source)), source))}
    return json.dumps(rules, ensure_ascii=False, indent=2) + "\n"


def compiled_api_module():
    return "// Generated by scripts/build_locales.py.\nexport default " + compiled_api_rules().rstrip() + ";\n"


if __name__ == "__main__":
    (ROOT / "static/locales/en.js").write_text(compiled_catalog())
    (ROOT / "static/locales/api.json").write_text(compiled_api_rules())
    (ROOT / "static/locales/api.js").write_text(compiled_api_module())
